"""Audit player attributes in the warehouse: coverage, sources and what to hand-check.

Players in scope are those with ratings (IPL and Full Member T20I matches). Coverage is
reported per player and weighted by balls, because a missing style for a bowler of 3,000
balls matters more than for one of 6. The hand-check queue lists in-scope players missing
an attribute that matters for them (a bowling style only for someone who bowled), most
balls first: fill them in ``config/reference/player_attribute_overrides.csv``.

Run with ``make attributes-audit`` after ``make dbt``; writes ``reports/player_attributes.md``.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import duckdb
import pandas as pd

ATTRIBUTES = ["date_of_birth", "nationality", "batting_hand", "bowling_kind", "bowling_arm"]
QUEUE_LENGTH = 40

IN_SCOPE_BALLS = """
    with balls as (
        select batter_id as player_id, 1 as faced, 0 as bowled from fact_delivery
        where (competition = 'ipl' or is_full_member_t20i) and not is_super_over
        union all
        select bowler_id, 0, 1 from fact_delivery
        where (competition = 'ipl' or is_full_member_t20i) and not is_super_over
    )
    select p.*, sum(b.faced) as faced, sum(b.bowled) as bowled
    from dim_player p
    join balls b using (player_id)
    where p.player_id in (select player_id from player_ratings_asof)
    group by all
"""


@dataclass(frozen=True)
class AttributesAudit:
    coverage: pd.DataFrame
    nationality_sources: pd.DataFrame
    hand_check_queue: pd.DataFrame


def audit(con: duckdb.DuckDBPyConnection) -> AttributesAudit:
    players = con.sql(IN_SCOPE_BALLS).df()
    # batting hand matters per ball faced, bowling style per ball bowled, the rest per ball
    weights = {"batting_hand": "faced", "bowling_kind": "bowled", "bowling_arm": "bowled"}
    rows = []
    for attr in ATTRIBUTES:
        w = players[weights[attr]] if attr in weights else players["faced"] + players["bowled"]
        known = players[attr].notna()
        rows.append(
            {
                "attribute": attr,
                "players": len(players),
                "players_with": int(known.sum()),
                "ball_share": float(w[known].sum() / w.sum()) if w.sum() else 0.0,
            }
        )
    sources = (
        players["nationality_source"]
        .fillna("none")
        .value_counts()
        .rename_axis("source")
        .reset_index(name="players")
    )
    # A gap only counts where the attribute matters: DBpedia rightly has no bowling style
    # for someone who never bowls. `balls` is the balls behind the player's gaps.
    total = players["faced"] + players["bowled"]
    relevant = {a: players[weights[a]] if a in weights else total for a in ATTRIBUTES}
    gaps = pd.DataFrame({a: players[a].isna() & (relevant[a] > 0) for a in ATTRIBUTES})
    players["missing"] = gaps.apply(lambda r: ", ".join(a for a in ATTRIBUTES if r[a]), axis=1)
    players["balls"] = pd.concat([relevant[a].where(gaps[a], 0) for a in ATTRIBUTES], axis=1).max(
        axis=1
    )
    queue = (
        players[players["missing"] != ""]
        .sort_values(["balls", "player_id"], ascending=[False, True])
        .head(QUEUE_LENGTH)[["player_id", "player_name", "key_cricinfo", "balls", "missing"]]
        .reset_index(drop=True)
    )
    return AttributesAudit(pd.DataFrame(rows), sources, queue)


def render_markdown(result: AttributesAudit) -> str:
    coverage = result.coverage.assign(
        ball_share=lambda d: (d["ball_share"] * 100).map("{:.1f}%".format)
    )
    lines = [
        "# Player attributes audit",
        "",
        "Generated by `make attributes-audit` from the warehouse; do not edit by hand.",
        "Players in scope: those with ratings (IPL and Full Member T20I matches).",
        "",
        "## Coverage",
        "",
        "`ball_share`: share of balls (faced for batting hand, bowled for bowling style,",
        "both otherwise) by players whose attribute is known.",
        "",
        coverage.to_markdown(index=False),
        "",
        "## Where nationality came from",
        "",
        result.nationality_sources.to_markdown(index=False),
        "",
        f"## Hand-check queue (top {QUEUE_LENGTH} by balls)",
        "",
        "`balls`: the balls behind the gaps (bowled for a bowling style, faced for batting",
        "hand). Add a row per missing field to `config/reference/player_attribute_overrides.csv`,",
        "with the source URL you checked.",
        "",
        result.hand_check_queue.to_markdown(index=False),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    repo = Path(__file__).resolve().parents[2]
    with duckdb.connect(str(repo / "data" / "warehouse.duckdb"), read_only=True) as con:
        result = audit(con)
    out = repo / "reports" / "player_attributes.md"
    out.write_text(render_markdown(result))
    print(result.coverage.to_string(index=False))
    print(f"wrote {out.relative_to(repo)}")


if __name__ == "__main__":
    main()
