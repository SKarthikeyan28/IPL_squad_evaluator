"""Data quality report: what was loaded, what was quarantined and why, per season.

Built only from the files the silver build wrote, so every number in the report comes
from the data, never from hand-entered figures. Run with ``make quality-report``.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

GROUP = ["season", "competition"]


def season_summary(silver: Path) -> pd.DataFrame:
    """One row per season and competition: clean matches, quarantined matches,
    deliveries kept, and error / warning counts from the violations log."""
    matches = pd.read_parquet(silver / "matches", columns=["match_id", "competition", "season"])
    matches["season"] = matches["season"].astype("int64")
    quarantined = pd.read_parquet(silver / "_quarantine" / "matches")
    deliveries = pd.read_parquet(silver / "deliveries", columns=["match_id"])
    violations = pd.read_parquet(silver / "_violations")

    all_matches = pd.concat([matches, quarantined[["match_id", "competition", "season"]]])
    competition_of = all_matches.set_index("match_id")["competition"]
    violations["competition"] = violations["match_id"].map(competition_of)

    parts = [
        matches.groupby(GROUP).size().rename("matches"),
        quarantined.groupby(GROUP).size().rename("quarantined"),
        deliveries.merge(matches, on="match_id").groupby(GROUP).size().rename("deliveries"),
    ]
    for severity, name in (("error", "errors"), ("warn", "warnings")):
        v = violations[violations["severity"] == severity]
        parts.append(v.groupby(GROUP).size().rename(name))

    summary = pd.concat(parts, axis=1).fillna(0).astype("int64").reset_index()
    return summary.sort_values(GROUP, ignore_index=True)


def render_markdown(silver: Path, snapshot_id: str) -> str:
    summary = season_summary(silver)
    # explicit order, so the report never depends on how files happen to be laid out
    violations = pd.read_parquet(silver / "_violations")
    violations["season"] = violations["season"].astype("int64")
    violations = violations.sort_values(
        ["severity", "season", "match_id", "table", "rule", "failure_case"], ignore_index=True
    )
    failures = pd.concat(
        [
            pd.read_parquet(silver / "_index_failures"),
            pd.read_parquet(silver / "_parse_failures").drop(columns="season"),
        ],
        ignore_index=True,
    )
    quarantined = pd.read_parquet(silver / "_quarantine" / "matches")

    lines = [
        "# Data quality report",
        "",
        "Generated by `make quality-report` from the silver build; do not edit by hand.",
        "",
        f"- Raw data snapshot: `{snapshot_id}`",
        f"- Matches loaded: {summary['matches'].sum():,}",
        f"- Matches quarantined (broke an `error` rule): {len(quarantined):,}",
        f"- Files that could not be parsed: {len(failures):,}",
        f"- Warnings (kept, flagged): {(violations['severity'] == 'warn').sum():,}",
        "",
        "## Per season",
        "",
        "| Season | Competition | Matches | Quarantined | Deliveries | Errors | Warnings |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in summary.itertuples(index=False):
        lines.append(
            f"| {r.season} | {r.competition} | {r.matches} | {r.quarantined} "
            f"| {r.deliveries:,} | {r.errors} | {r.warnings} |"
        )

    lines += ["", "## Quarantined matches", ""]
    if quarantined.empty:
        lines.append("None.")
    else:
        lines += ["| Match | Season | Rules broken |", "|---|---|---|"]
        for r in quarantined.sort_values(["season", "match_id"]).itertuples(index=False):
            lines.append(f"| {r.match_id} | {r.season} | {r.quarantine_rules} |")

    lines += ["", "## Rule counts", "", "| Severity | Rule | Count |", "|---|---|---|"]
    counts = violations.groupby(["severity", "table", "rule"]).size().reset_index(name="n")
    for r in counts.itertuples(index=False):
        lines.append(f"| {r.severity} | {r.table}.{r.rule} | {r.n} |")

    lines += [
        "",
        "## Every violation",
        "",
        "| Severity | Match | Season | Rule | Detail |",
        "|---|---|---|---|---|",
    ]
    for r in violations.itertuples(index=False):
        lines.append(
            f"| {r.severity} | {r.match_id} | {r.season} | {r.table}.{r.rule} | {r.failure_case} |"
        )

    if not failures.empty:
        lines += ["", "## Unparseable files", "", "| File | Error | Reason |", "|---|---|---|"]
        for r in failures.itertuples(index=False):
            lines.append(f"| {r.source}/{r.member} | {r.error_type} | {r.reason} |")

    return "\n".join(lines) + "\n"


def main() -> None:
    from cricket_value.ingest.manifest import Manifest

    repo = Path(__file__).resolve().parents[2]
    snapshot = Manifest(repo / "data" / "raw" / "manifest").snapshot_id()
    out = repo / "reports" / "data_quality.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(render_markdown(repo / "data" / "silver", snapshot))
    print(f"wrote {out.relative_to(repo)}")


if __name__ == "__main__":
    main()
