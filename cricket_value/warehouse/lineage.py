"""The dbt lineage graph as Mermaid, kept in README.md between two markers.

``make lineage`` parses the dbt project (no database needed) and rewrites the block; a
test fails when the README's graph no longer matches the project. Sources are grouped as
silver, the reference seeds are drawn as one node, and dbt tests are left out.

Run with ``make lineage``; rewrites the lineage block of ``README.md``.
"""

from __future__ import annotations

import json
import re
import tempfile
from pathlib import Path
from typing import Any

from cricket_value.warehouse.dbt import REPO, run_dbt

START = "<!-- lineage:start (generated by `make lineage`; do not edit) -->"
END = "<!-- lineage:end -->"
SEEDS = "reference seeds"
LAYERS = ["silver", "seeds", "staging", "intermediate", "ratings", "marts"]


def _name(unique_id: str, nodes: dict[str, Any]) -> tuple[str, str] | None:
    """(layer, display name) of a manifest node, or None if it isn't lineage."""
    kind = unique_id.split(".")[0]
    if kind == "source":
        _, _, source, table = unique_id.split(".")
        return "silver", f"{source}.{table}"
    if kind == "seed":
        return "seeds", SEEDS
    if kind == "model":
        fqn = nodes[unique_id]["fqn"]
        return fqn[2] if len(fqn) > 3 else fqn[1], fqn[-1]
    return None


def manifest_lineage(
    manifest: dict[str, Any],
) -> tuple[dict[str, list[str]], list[tuple[str, str]]]:
    """Display names per layer (in pipeline order) and sorted, de-duplicated edges."""
    nodes = manifest["nodes"]
    layers: dict[str, set[str]] = {}
    edges: set[tuple[str, str]] = set()
    for uid in [*manifest["sources"], *nodes]:
        named = _name(uid, nodes)
        if named is None:
            continue
        layer, name = named
        layers.setdefault(layer, set()).add(name)
        for dep in nodes.get(uid, {}).get("depends_on", {}).get("nodes", []):
            upstream = _name(dep, nodes)
            if upstream is not None:
                edges.add((upstream[1], name))
    ordered = {layer: sorted(layers[layer]) for layer in LAYERS if layer in layers}
    return ordered, sorted(edges)


def _id(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def mermaid(manifest: dict[str, Any]) -> str:
    layers, edges = manifest_lineage(manifest)
    lines = ["```mermaid", "flowchart LR"]
    for layer, names in layers.items():
        lines.append(f"  subgraph {layer}")
        lines += [f'    {_id(n)}["{n}"]' for n in names]
        lines.append("  end")
    lines += [f"  {_id(a)} --> {_id(b)}" for a, b in edges]
    lines.append("```")
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """``text`` with the lines between START and END replaced by ``block``."""
    pattern = re.compile(re.escape(START) + r"\n(?:.*?\n)?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise ValueError("lineage markers not found")
    return pattern.sub(lambda _: f"{START}\n{block}\n{END}", text, count=1)


def parse_manifest(work_dir: Path) -> dict[str, Any]:
    """``dbt parse`` the project into ``work_dir`` and load its manifest."""
    result = run_dbt(
        ["parse"],
        silver_dir=work_dir / "silver",
        warehouse=work_dir / "unused.duckdb",
        work_dir=work_dir,
    )
    assert result.success, result.exception
    manifest: dict[str, Any] = json.loads((work_dir / "target" / "manifest.json").read_text())
    return manifest


def main() -> None:
    readme = REPO / "README.md"
    with tempfile.TemporaryDirectory() as tmp:
        chart = mermaid(parse_manifest(Path(tmp)))
    readme.write_text(replace_block(readme.read_text(), chart))
    print(f"wrote lineage to {readme.relative_to(REPO)}")


if __name__ == "__main__":
    main()
