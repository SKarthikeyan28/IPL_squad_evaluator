"""Audit the hand-maintained reference data against the match data.

Sources say which grounds were home grounds; the data shows where teams actually played.
Where the two disagree, a human should look. The audit never changes the reference data.

Checks:

- ``unmapped_team`` / ``unmapped_venue`` (error): an IPL name with no alias row.
- ``missing_home_venue`` (warn): in a non-neutral season, one franchise played every
  league match (at least 2) at a ground that isn't on its home list.
- ``unused_home_venue`` (warn): a home-venue row that no match ever used.
- ``no_home_games`` (warn): a franchise had no home game in a non-neutral season.

Run with ``make reference-audit``; writes ``reports/reference_audit.md``.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from cricket_value.reference.home import match_home_status
from cricket_value.reference.reference import Reference, load_reference

COLUMNS = ["severity", "check", "season", "franchise_id", "venue_id", "detail"]


def audit(matches: pd.DataFrame, ref: Reference) -> pd.DataFrame:
    ipl = matches[matches["competition"] == "ipl"]
    home = match_home_status(ipl, ref)
    findings: list[dict[str, object]] = []

    def add(severity: str, check: str, detail: str, **keys: object) -> None:
        findings.append({"severity": severity, "check": check, "detail": detail, **keys})

    for name in sorted(set(home.loc[home["franchise_id"].isna(), "team"])):
        add("error", "unmapped_team", f"team name {name!r} has no alias")
    venue_of = ipl.set_index("match_id")["venue_name"]
    for name in sorted(set(venue_of[home.loc[home["venue_id"].isna(), "match_id"]])):
        add("error", "unmapped_venue", f"venue name {name!r} has no alias")

    normal = home[~home["in_neutral_period"].astype(bool) & home["franchise_id"].notna()]
    stage = ipl.set_index("match_id")["event_stage"]
    league = normal[normal["match_id"].map(stage).isna()]

    # Grounds where one franchise played every league match
    per_ground = league.groupby(["season", "venue_id"])["match_id"].nunique().rename("matches")
    per_team = league.groupby(["season", "venue_id", "franchise_id"])["match_id"].nunique()
    dominant = per_team.rename("played").reset_index().join(per_ground, on=["season", "venue_id"])
    dominant = dominant[(dominant["played"] == dominant["matches"]) & (dominant["matches"] >= 2)]
    at_home = normal[normal["team_at_home"].astype(bool)]
    listed = set(zip(at_home["season"], at_home["venue_id"], at_home["franchise_id"], strict=True))
    for r in dominant.itertuples():
        if (r.season, r.venue_id, r.franchise_id) not in listed:
            add(
                "warn",
                "missing_home_venue",
                f"played all {r.matches} league matches there but it isn't a listed home venue",
                season=r.season,
                franchise_id=r.franchise_id,
                venue_id=r.venue_id,
            )

    used = set(zip(at_home["franchise_id"], at_home["venue_id"], at_home["season"], strict=True))
    for row in ref.home_venues.to_dict("records"):
        first = int(row["first_season"])
        last = int(row["last_season"]) if pd.notna(row["last_season"]) else None
        if not any(
            f == row["franchise_id"]
            and v == row["venue_id"]
            and first <= s <= (last if last is not None else s)
            for f, v, s in used
        ):
            add(
                "warn",
                "unused_home_venue",
                f"no home match found for {first}-{last if last is not None else ''}",
                franchise_id=row["franchise_id"],
                venue_id=row["venue_id"],
            )

    counts = normal.assign(is_home=normal["home_status"] == "home")
    counts = counts.groupby(["season", "franchise_id"])["is_home"].sum().reset_index()
    for r in counts[counts["is_home"] == 0].itertuples():
        add(
            "warn",
            "no_home_games",
            "no home game in a non-neutral season",
            season=r.season,
            franchise_id=r.franchise_id,
        )

    out = pd.DataFrame(findings, columns=COLUMNS)
    return out.sort_values(
        ["severity", "check", "season", "franchise_id"], na_position="first", ignore_index=True
    )


def home_counts(matches: pd.DataFrame, ref: Reference) -> pd.DataFrame:
    """Home games per franchise per season (all stages), for the report."""
    home = match_home_status(matches[matches["competition"] == "ipl"], ref)
    home = home[home["home_status"] == "home"]
    return home.pivot_table(
        index="franchise_id", columns="season", values="match_id", aggfunc="count", fill_value=0
    )


def render_markdown(findings: pd.DataFrame, counts: pd.DataFrame) -> str:
    lines = [
        "# Reference data audit",
        "",
        "Generated by `make reference-audit`: the sourced reference data in `config/reference/`",
        "checked against where matches were actually played. Do not edit by hand.",
        "",
        f"- Errors: {(findings['severity'] == 'error').sum()}",
        f"- Warnings: {(findings['severity'] == 'warn').sum()}",
        "",
        "## Findings",
        "",
    ]
    if findings.empty:
        lines.append("None.")
    else:
        lines += [
            "| Severity | Check | Season | Franchise | Venue | Detail |",
            "|---|---|---|---|---|---|",
        ]
        for r in findings.fillna("").itertuples(index=False):
            cells = [r.severity, r.check, r.season, r.franchise_id, r.venue_id, r.detail]
            lines.append("| " + " | ".join(str(c) for c in cells) + " |")
    lines += ["", "## Home games per franchise and season", "", counts.to_markdown(), ""]
    return "\n".join(lines)


def main() -> None:
    repo = Path(__file__).resolve().parents[2]
    ref = load_reference(repo / "config" / "reference")
    matches = pd.read_parquet(repo / "data" / "silver" / "matches")
    matches["season"] = matches["season"].astype("int64")
    findings = audit(matches, ref)
    out = repo / "reports" / "reference_audit.md"
    out.write_text(render_markdown(findings, home_counts(matches, ref)))
    print(findings.to_string(index=False) if not findings.empty else "no findings")
    print(f"wrote {out.relative_to(repo)}")


if __name__ == "__main__":
    main()
